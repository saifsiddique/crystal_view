/**
 * Space-group operations (R, t): x' = R x + t, with R an integer matrix acting on fractional
 * coordinates. Parsing is exact for the usual fractions (no eval), and `closure` completes a set of
 * generators to a group modulo lattice translations.
 */
import { SymmetryError } from '../errors';
import { identity, mul, mulVec, type Mat3 } from '../math/mat3';
import type { Vec3 } from '../math/vec3';

export interface SymOp {
  readonly R: Mat3;
  readonly t: Vec3;
}

export const IDENTITY_OP: SymOp = { R: identity, t: [0, 0, 0] };

/** Translations within 5e-4 of a multiple of 1/24 are snapped to it ('0.3333' means 1/3). */
export function snapTranslation(t: number): number {
  const r = Math.round(t * 24) / 24;
  return Math.abs(t - r) < 5e-4 ? r : t;
}

const AXES: Record<string, number> = { x: 0, y: 1, z: 2 };
const NUMBER = /^(\d+(?:\.\d*)?|\.\d+)(?:\/(\d+))?/;

function parseRow(part: string, whole: string): { row: [number, number, number]; t: number } {
  const s = part.replace(/\s+/g, '').toLowerCase();
  const fail = (why: string): never => {
    throw new SymmetryError(`Cannot read symmetry operation "${whole}": ${why}.`);
  };
  if (s === '') return fail('empty component');
  const row: [number, number, number] = [0, 0, 0];
  let t = 0;
  let i = 0;
  while (i < s.length) {
    let sign = 1;
    if (s[i] === '+' || s[i] === '-') {
      sign = s[i] === '-' ? -1 : 1;
      i++;
    }
    const m = NUMBER.exec(s.slice(i));
    let coef = 1;
    if (m) {
      coef = Number(m[1]);
      if (m[2] !== undefined) {
        if (Number(m[2]) === 0) return fail('division by zero');
        coef /= Number(m[2]);
      }
      i += m[0].length;
      if (s[i] === '*') i++;
    }
    const axis = AXES[s[i]];
    if (axis !== undefined) {
      if (!Number.isInteger(coef)) return fail('non-integer coefficient of x, y or z');
      row[axis] += sign * coef;
      i++;
    } else if (m) {
      t += sign * coef;
    } else {
      return fail(`unexpected "${s[i]}"`);
    }
  }
  return { row, t: snapTranslation(t) };
}

/** Parse '-x+1/2, y, z+1/4', 'x-y,x,z+1/6', '+x,+y,+z', '1/2+x, ...'. */
export function parseSymop(text: string): SymOp {
  const parts = text.split(',');
  if (parts.length !== 3) {
    throw new SymmetryError(`Cannot read symmetry operation "${text}": expected three components.`);
  }
  const rows = parts.map((p) => parseRow(p, text));
  const R: Mat3 = [rows[0].row, rows[1].row, rows[2].row];
  return { R, t: [rows[0].t, rows[1].t, rows[2].t] };
}

export const applyOp = (op: SymOp, f: Vec3): Vec3 => {
  const r = mulVec(op.R, f);
  return [r[0] + op.t[0], r[1] + op.t[1], r[2] + op.t[2]];
};

/** a after b: (a∘b)(x) = a(b(x)). */
export function composeOps(a: SymOp, b: SymOp): SymOp {
  const bt = mulVec(a.R, b.t);
  return { R: mul(a.R, b.R), t: [bt[0] + a.t[0], bt[1] + a.t[1], bt[2] + a.t[2]] };
}

const wrap = (x: number): number => {
  const w = x - Math.floor(x + 1e-9);
  return w < 1e-9 ? 0 : w;
};

/** The operation with translation reduced to [0, 1). */
export const wrapOp = (op: SymOp): SymOp => ({
  R: op.R,
  t: [wrap(op.t[0]), wrap(op.t[1]), wrap(op.t[2])],
});

/** Identity of an operation modulo lattice translations, for de-duplication. */
export function opKey(op: SymOp): string {
  const t = op.t.map((x) => Math.round(wrap(x) * 1e4) % 1e4);
  return `${op.R[0].join()},${op.R[1].join()},${op.R[2].join()};${t.join()}`;
}

/** Remove duplicate operations (same R, same t modulo 1), keeping the first of each. */
export function uniqueOps(ops: readonly SymOp[]): SymOp[] {
  const seen = new Set<string>();
  const out: SymOp[] = [];
  for (const op of ops) {
    const key = opKey(op);
    if (!seen.has(key)) {
      seen.add(key);
      out.push(wrapOp(op));
    }
  }
  return out;
}

/** Largest space-group order including centring (Fm-3m: 192). */
export const MAX_GROUP_ORDER = 192;

/**
 * The group generated by `generators`, modulo lattice translations, starting from the identity.
 * Throws `SymmetryError` if it grows past a physically possible size (not a crystallographic group).
 */
export function closure(generators: readonly SymOp[]): SymOp[] {
  const gens = uniqueOps(generators);
  const group = new Map<string, SymOp>();
  const start = wrapOp(IDENTITY_OP);
  group.set(opKey(start), start);
  const queue: SymOp[] = [start];
  for (let head = 0; head < queue.length; head++) {
    const g = queue[head];
    for (const h of gens) {
      const p = wrapOp(composeOps(h, g));
      const key = opKey(p);
      if (!group.has(key)) {
        if (group.size >= MAX_GROUP_ORDER) {
          throw new SymmetryError(
            `The symmetry operations generate more than ${MAX_GROUP_ORDER} elements: not a space group.`,
          );
        }
        group.set(key, p);
        queue.push(p);
      }
    }
  }
  return [...group.values()];
}

function fraction(x: number): string {
  for (const d of [1, 2, 3, 4, 6, 8, 12, 24]) {
    const n = Math.round(x * d);
    if (Math.abs(x * d - n) < 1e-6) return d === 1 ? String(n) : `${n}/${d}`;
  }
  return x.toFixed(4);
}

/** Text form 'x-y+1/2, ...' for display and export; `parseSymop` reads it back. */
export function formatSymop(op: SymOp): string {
  return op.R.map((row, i) => {
    let s = '';
    ['x', 'y', 'z'].forEach((v, j) => {
      const c = row[j];
      if (c === 0) return;
      s += (c < 0 ? '-' : s === '' ? '' : '+') + (Math.abs(c) === 1 ? '' : Math.abs(c)) + v;
    });
    const t = op.t[i];
    if (Math.abs(t) > 1e-9) s += (t < 0 ? '-' : s === '' ? '' : '+') + fraction(Math.abs(t));
    return s === '' ? '0' : s;
  }).join(', ');
}
