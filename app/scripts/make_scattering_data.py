"""Generate the scattering-factor and element-property tables for core/scattering.

    python -I scripts/make_scattering_data.py        (run from app/, env s-em)

The numbers are published parameters, copied from the packages that ship them; the unit tests
check them independently (Mott-Bethe consistency between three tables, f(0) = Z, Sears values).

  xray.ts       Waasmaier & Kirfel, Acta Cryst. A51 (1995) 416: f(s) = sum_i a_i exp(-b_i s^2) + c,
                s = sin(theta)/lambda in 1/A. Neutral atoms and ions. From abTEM's JSON copy.
  electron.ts   Lobato & Van Dyck, Acta Cryst. A70 (2014) 636 (103 elements):
                f_e(q) = sum_i a_i (2 + b_i q^2) / (1 + b_i q^2)^2, q = 1/d = 2 s, result in angstrom.
                Peng, Ren, Dudarev & Whelan, Acta Cryst. A52 (1996) 257: five-Gaussian fits for
                neutral atoms (s < 2 and 2 < s < 6, 1/A) and for ions (s < 2).  From abTEM's JSON copy.
  elements.ts   symbol, Z, name, atomic mass (ASE/IUPAC), covalent radius (Cordero et al. 2008),
                van der Waals radius (Alvarez 2013), Jmol colour, Shannon ionic radii (pymatgen),
                Sears (1992) coherent neutron scattering length (real part, fm; pymatgen's copy),
                including the isotopes 2H (D) and 3H (T).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
from ase.data import atomic_masses, chemical_symbols, covalent_radii
from ase.data.colors import jmol_colors
from ase.data.vdw_alvarez import vdw_radii
from pymatgen.analysis.diffraction.neutron import ATOMIC_SCATTERING_LEN
from pymatgen.core import Element

import abtem

APP = Path(__file__).resolve().parent.parent
OUT = APP / "src" / "core" / "scattering" / "data"
OUT.mkdir(parents=True, exist_ok=True)
DATA = Path(abtem.__file__).parent / "parametrizations" / "data"
NL = chr(10)


def load(name: str):
    return json.loads((DATA / f"{name}.json").read_text())


def num(x) -> float:
    return float(f"{float(x):.10g}")


def write(name: str, header: str, body: str) -> None:
    (OUT / name).write_text(header + body, encoding="utf-8", newline=NL)


def literal(obj) -> str:
    return json.dumps(obj, separators=(",", ":"))


GENERATED = "// GENERATED by scripts/make_scattering_data.py. Do not edit." + NL

# ---- X-ray: Waasmaier-Kirfel ----------------------------------------------------------------------
wk = load("waasmaier_kirfel")
# Stored as [a1..a5, c, b1..b5] (abTEM's layout, checked against f(0) = Z in the tests).
xray = {k: [num(v) for v in vals] for k, vals in wk.items() if "*" not in k}
write(
    "xray.ts",
    GENERATED
    + "// Waasmaier & Kirfel, Acta Cryst. A51 (1995) 416-431. f(s) = sum_i a_i exp(-b_i s^2) + c, s = sin(theta)/lambda."
    + NL
    + "// Row layout: [a1, a2, a3, a4, a5, c, b1, b2, b3, b4, b5]. Ions are keyed 'Fe++', 'O--', 'Si++++'."
    + NL,
    "export const WAASMAIER_KIRFEL: Readonly<Record<string, readonly number[]>> = "
    + literal(xray)
    + ";"
    + NL,
)

# ---- electron: Lobato-Van Dyck and Peng ------------------------------------------------------------
lobato = {k: [num(v) for v in (np.array(p).ravel())] for k, p in load("lobato").items()}
peng_low = {k: [num(v) for v in np.array(p).ravel()] for k, p in load("peng_low").items()}
peng_high = {k: [num(v) for v in np.array(p).ravel()] for k, p in load("peng_high").items()}
peng_ion = {k: [num(v) for v in np.array(p).ravel()] for k, p in load("peng_ionic").items()}
write(
    "electron.ts",
    GENERATED
    + "// Lobato & Van Dyck, Acta Cryst. A70 (2014) 636-649: f_e(q) = sum a_i (2 + b_i q^2)/(1 + b_i q^2)^2, q = 1/d (angstrom^-1)."
    + NL
    + "// Row: [a1..a5 (angstrom), b1..b5 (angstrom^2)]."
    + NL
    + "// Peng, Ren, Dudarev & Whelan, Acta Cryst. A52 (1996) 257-276: f_e(s) = sum a_i exp(-b_i s^2), s = sin(theta)/lambda."
    + NL
    + "// Row: [a1..a5 (angstrom), b1..b5 (angstrom^2)]. PENG_LOW is valid for s < 2, PENG_HIGH for 2 < s < 6, PENG_IONIC for s < 2."
    + NL,
    "export const LOBATO: Readonly<Record<string, readonly number[]>> = " + literal(lobato) + ";" + NL
    + "export const PENG_LOW: Readonly<Record<string, readonly number[]>> = " + literal(peng_low) + ";" + NL
    + "export const PENG_HIGH: Readonly<Record<string, readonly number[]>> = " + literal(peng_high) + ";" + NL
    + "export const PENG_IONIC: Readonly<Record<string, readonly number[]>> = " + literal(peng_ion) + ";" + NL,
)

# ---- elements --------------------------------------------------------------------------------------
rows = []
for z in range(1, 119):
    sym = chemical_symbols[z]
    el = Element(sym)
    try:
        ionic = {int(k): num(str(v).split()[0]) for k, v in el.ionic_radii.items()}
    except Exception:
        ionic = {}
    # Jmol defines colours up to Z = 109; heavier elements get its default magenta.
    r, g, b = (int(round(c * 255)) for c in jmol_colors[z]) if z < len(jmol_colors) else (255, 20, 147)
    vdw = float(vdw_radii[z]) if z < len(vdw_radii) and not np.isnan(vdw_radii[z]) else None
    rows.append(
        {
            "Z": z,
            "symbol": sym,
            "name": el.long_name,
            "mass": num(atomic_masses[z]),
            "covalent": num(covalent_radii[z]),
            "vdw": None if vdw is None else num(vdw),
            "color": f"#{r:02x}{g:02x}{b:02x}",
            "ionic": ionic,
            "b": ATOMIC_SCATTERING_LEN.get(sym),
        }
    )
assert [r["symbol"] for r in rows][:3] == ["H", "He", "Li"]
isotopes = {k: v for k, v in ATOMIC_SCATTERING_LEN.items() if re.match(r"^\d+[A-Z]", k) and k in ("1H", "2H", "3H")}
write(
    "elements.ts",
    GENERATED
    + "// Masses: IUPAC via ASE. Covalent radii: Cordero et al., Dalton Trans. (2008) 2832. van der Waals radii: Alvarez, Dalton Trans. 42 (2013) 8617."
    + NL
    + "// Colours: Jmol. Ionic radii (angstrom, by oxidation state): Shannon, Acta Cryst. A32 (1976) 751, via pymatgen."
    + NL
    + "// b: coherent neutron scattering length in fm, real part (Sears, Neutron News 3 (1992) 26, via pymatgen); null if unknown."
    + NL
    + "export interface ElementRow {"
    + NL
    + "  readonly Z: number;"
    + NL
    + "  readonly symbol: string;"
    + NL
    + "  readonly name: string;"
    + NL
    + "  readonly mass: number;"
    + NL
    + "  readonly covalent: number;"
    + NL
    + "  readonly vdw: number | null;"
    + NL
    + "  readonly color: string;"
    + NL
    + "  readonly ionic: Readonly<Record<number, number>>;"
    + NL
    + "  readonly b: number | null;"
    + NL
    + "}"
    + NL
    + NL,
    "export const ELEMENT_ROWS: readonly ElementRow[] = "
    + literal(rows)
    + ";"
    + NL
    + "/** Isotope neutron scattering lengths in fm (Sears 1992). */"
    + NL
    + "export const ISOTOPE_B: Readonly<Record<string, number>> = "
    + literal(isotopes)
    + ";"
    + NL
    + "/** Isotope masses in u. */"
    + NL
    + "export const ISOTOPE_MASS: Readonly<Record<string, number>> = {'1H':1.00782503207,'2H':2.0141017778,'3H':3.0160492777};"
    + NL,
)
print(len(rows), "elements;", len(xray), "X-ray species;", len(lobato), "Lobato;", isotopes)
