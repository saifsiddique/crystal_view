"""Generate the space-group table used by core/symmetry (Hall symbols + names) and the reference
operation checksums the unit tests compare our Hall-symbol parser against.

    python -I scripts/make_spacegroup_table.py        (run from app/, env s-em with spglib)

Outputs
  src/core/symmetry/data/spacegroups.ts   one row per Hall setting (530):
        [hall_number, it_number, hall_symbol, international_short, international_full, choice]
  tests/fixtures/spacegroup_ops.json        per hall_number: {n, hash} of spglib's operation set,
        translations in twelfths (all 530 settings use denominators dividing 12).

Source: spglib's space-group database (BSD licence); Hall symbols are public (Hall 1981).
"""

from __future__ import annotations

import json
from importlib.metadata import version
from pathlib import Path

import spglib

APP = Path(__file__).resolve().parent.parent


def fnv1a(text: str) -> str:
    h = 0x811C9DC5
    for ch in text.encode():
        h = ((h ^ ch) * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


rows, ops = [], {}
for hall in range(1, 531):
    t = spglib.get_spacegroup_type(hall)
    rows.append([hall, t.number, t.hall_symbol, t.international_short, t.international_full, t.choice])
    sym = spglib.get_symmetry_from_database(hall)
    strings = []
    for r, tr in zip(sym["rotations"], sym["translations"]):
        t12 = [round(x * 12) for x in tr]
        assert all(abs(x * 12 - round(x * 12)) < 1e-6 for x in tr), (hall, tr)
        strings.append(",".join(str(int(v)) for v in r.flatten()) + ";" + ",".join(str(v % 12) for v in t12))
    strings.sort()
    ops[str(hall)] = {"n": len(strings), "hash": fnv1a("|".join(strings))}

NL = chr(10)
header = (
    "// GENERATED by scripts/make_spacegroup_table.py from spglib's space-group database (BSD licence)." + NL
    + "// Do not edit. Row: [hall_number, it_number, hall_symbol, international_short, international_full, choice]" + NL
)
body = "export type SpaceGroupRow = readonly [number, number, string, string, string, string];" + NL + NL
body += "export const SPACE_GROUP_ROWS: readonly SpaceGroupRow[] = " + json.dumps(rows, separators=(",", ":")) + ";" + NL
(APP / "src/core/symmetry/data/spacegroups.ts").write_text(header + body, encoding="utf-8", newline=NL)
(APP / "tests/fixtures/spacegroup_ops.json").write_text(
    json.dumps({"spglib": version("spglib"), "ops": ops}, separators=(",", ":"))
)
print(len(rows), "settings")
